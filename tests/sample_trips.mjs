// Runs sample trips through the same search, router and time model the app uses.
// Usage: node tests/sample_trips.mjs            (prints results)
//        node tests/sample_trips.mjs --md       (writes docs/sample_trips.md)
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createRouter } from "../web/js/router.js";
import { createTimeModel, formatRange } from "../web/js/timeModel.js";
import { createSearch } from "../web/js/search.js";

const root = new URL("..", import.meta.url);
const net = JSON.parse(readFileSync(new URL("web/data/network.json", root)));
const tm = createTimeModel(JSON.parse(readFileSync(new URL("web/data/time_model_v0.json", root))));
const router = createRouter(net, tm);
const search = createSearch(net);

// [from, to, band] — mix of outer-GAMA (2021) and central-Accra (2015) corridors
const TRIPS = [
  ["Madina", "Circle", 0],
  ["Kasoa", "Kaneshie", 0],
  ["Ashaiman", "Tema Station", 1],
  ["Amasaman", "Achimota", 0],
  ["Adenta", "Accra Mall", 1],
  ["Kaneshie", "Osu", 1],
  ["Dansoman", "Circle", 2],
  ["Teshie", "37", 2],
  ["Madina", "Kasoa", 1],
  ["Lapaz", "Legon", 0],
  ["Dodowa", "Madina", 0],
  ["Nungua", "Kaneshie", 2],
];

const md = process.argv.includes("--md");
const lines = ["# Sample trips", "", `Data ${net.meta.version} · time model ${tm.id} · generated by \`node tests/sample_trips.mjs --md\``, ""];
let ok = 0;
for (const [a, b, band] of TRIPS) {
  const o = search.find(a)[0], d = search.find(b)[0];
  const head = `## ${a} → ${b} (${net.bands[band].label})`;
  lines.push(head, "", `Matched: **${o?.n ?? "—"}** (${net.districts[o?.d] ?? ""}) → **${d?.n ?? "—"}** (${net.districts[d?.d] ?? ""})`, "");
  if (!o || !d) { lines.push("No match for search text.", ""); continue; }
  const t0 = performance.now();
  const opts = router.plan(search.access(o), search.access(d), band);
  const ms = (performance.now() - t0).toFixed(0);
  if (opts.length) ok++;
  lines.push(`${opts.length} options in ${ms} ms`, "");
  for (const j of opts.slice(0, 4)) {
    const rides = j.legs.filter((l) => l.type === "ride").map((l) => {
      const p = net.patterns[l.pi];
      return `${p.name} [${p.src}] (${net.stops.n[p.s[l.from]]} → ${net.stops.n[p.s[l.to]]})`;
    });
    lines.push(`- **${formatRange(j.time)}**, ${j.transfers} transfer(s): ${rides.join(" ⇒ ")}`);
  }
  lines.push("");
}
lines.push(`**${ok}/${TRIPS.length} trips returned at least one option.**`);
const text = lines.join("\n");
if (md) {
  mkdirSync(new URL("docs", root), { recursive: true });
  writeFileSync(new URL("docs/sample_trips.md", root), text + "\n");
}
console.log(text);
